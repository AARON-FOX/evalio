import type { ReactNode } from "react";
import { Link, useLocation } from "react-router";
import { ArrowLeft, ArrowRight } from "lucide-react";
import { useAuth } from "../context/useAuth";
import styles from "./InformationPages.module.scss";

function InformationLayout({
  title,
  lead,
  children,
}: {
  title: string;
  lead: string;
  children: ReactNode;
}) {
  const { profile } = useAuth();
  const { pathname } = useLocation();
  const returnPath = profile ? "/dashboard" : "/login";
  return (
    <div className={styles.page}>
      <header className={styles.header}>
        <Link to={returnPath} className={styles.brand}>
          <span className={styles.mark}>e</span>evalio
        </Link>
        <Link to={returnPath} className={styles.back}>
          <ArrowLeft size={16} />
          {profile ? "До кабінету" : "До входу"}
        </Link>
      </header>
      <div className={styles.hero}>
        <p className={styles.eyebrow}>НАВЧАЛЬНИЙ ПРОСТІР · EVALIO</p>
        <h1>{title}</h1>
        <p className={styles.lead}>{lead}</p>
      </div>
      {children}
      <nav aria-label="Інформаційні сторінки" className={styles.links}>
        {pathname !== "/help" && (
          <Link className={styles.action} to="/help">
            Довідка <ArrowRight size={16} />
          </Link>
        )}
        {pathname !== "/privacy" && (
          <Link
            className={`${styles.action} ${styles.secondary}`}
            to="/privacy"
          >
            Конфіденційність
          </Link>
        )}
        {pathname !== "/terms" && (
          <Link className={`${styles.action} ${styles.secondary}`} to="/terms">
            Умови використання
          </Link>
        )}
      </nav>
    </div>
  );
}

